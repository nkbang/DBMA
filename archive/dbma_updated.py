def _model_supports_embeddings(model: str) -> bool:
    name = (model or "").lower()
    keywords = ["embed", "bge", "nomic", "mxbai", "e5", "snowflake"]
    return any(k in name for k in keywords)


def _embed_texts(texts: List[str], model: str = DEFAULT_EMBED_MODEL) -> List[List[float]]:
    try:
        return ollama.embed(model=model, input=texts)["embeddings"]
    except Exception as e:
        if "tokenize" in str(e).lower() or len(texts) > 1:
            out = []
            for t in texts:
                if not t.strip():
                    continue
                try:
                    out.extend(ollama.embed(model=model, input=t)["embeddings"])
                except Exception:
                    continue
            if out:
                return out
        raise


def _rag_noise(text: str) -> float:
    return estimate_noise_score(text)["score"]


def build_rag_store(
    selected_files: Optional[List[str]] = None,
    input_dir: str = str(OUTPUT_DIR),
    embed_model: str = DEFAULT_EMBED_MODEL,
    chunk_size: int = DEFAULT_CHUNK_SIZE,
    overlap: int = DEFAULT_CHUNK_OVERLAP,
    min_len: int = RAG_MIN_LEN,
    max_noise: float = RAG_MAX_NOISE,
):
    ensure_dirs()
    collection = get_collection()
    docs = read_indexable_docs(selected_files=selected_files, input_dir=input_dir)
    ids, documents, metadatas = [], [], []
    for doc in docs:
        chunks = rag_chunk_text(doc["text"], chunk_size=chunk_size, overlap=overlap)
        for j, chunk in enumerate(chunks):
            if len(chunk.strip()) < min_len:
                continue
            noise = _rag_noise(chunk)
            if noise >= max_noise:
                continue
            ids.append(f"{doc['source']}::{j}")
            documents.append(chunk)
            metadatas.append({"source": doc["source"], "chunk": j, "noise": noise, "len": len(chunk)})
    if not ids:
        return {"documents": len(docs), "chunks": 0, "indexed": 0, "collection": COLLECTION_NAME, "chroma_dir": str(CHROMA_DIR)}
    embeddings = _embed_texts(documents, model=embed_model)
    collection.upsert(ids=ids, embeddings=embeddings, documents=documents, metadatas=metadatas)
    return {"documents": len(docs), "chunks": len(documents), "indexed": len(ids), "collection": COLLECTION_NAME, "chroma_dir": str(CHROMA_DIR), "embed_model": embed_model}


def query_rag(
    question: str,
    embed_model: str = DEFAULT_EMBED_MODEL,
    gen_model: str = DEFAULT_GEN_MODEL,
    top_k: int = RAG_TOP_K,
    temperature: float = DEFAULT_TEMPERATURE,
    max_noise: float = RAG_MAX_NOISE,
) -> Dict[str, Any]:
    ensure_dirs()
    collection = get_collection()
    embedding_enabled = _model_supports_embeddings(embed_model)
    q_emb = None
    embed_error = None

    if embedding_enabled:
        try:
            q_emb = ollama.embed(model=embed_model, input=question)["embeddings"][0]
        except Exception as e:
            embed_error = str(e)
            embedding_enabled = False

    results = {"documents": [[]], "metadatas": [[]], "ids": [[]]}
    if q_emb is not None:
        try:
            results = collection.query(query_embeddings=[q_emb], n_results=top_k)
        except Exception as e:
            embed_error = f"{embed_error}; {e}" if embed_error else str(e)
            embedding_enabled = False

    docs = results.get("documents", [[]])[0]
    metas = results.get("metadatas", [[]])[0]
    ids = results.get("ids", [[]])[0]
    sources = []
    filtered_docs = []
    for i, doc in enumerate(docs):
        meta = metas[i] if i < len(metas) else {}
        source = meta.get("source", "unknown") if isinstance(meta, dict) else "unknown"
        chunk = meta.get("chunk", i) if isinstance(meta, dict) else i
        noise = meta.get("noise", None) if isinstance(meta, dict) else None
        if noise is not None and noise >= max_noise:
            continue
        filtered_docs.append(doc)
        sources.append({"rank": len(filtered_docs), "id": ids[i] if i < len(ids) else "", "source": source, "chunk": chunk, "noise": noise, "snippet": doc[:240].replace("\n", " ")})
    if filtered_docs:
        context = "\n\n".join(filtered_docs)
        prompt = f"""아래 문맥만 사용해 답하라. 모르면 모른다고 말하라.

문맥:
{context}

질문:
{question}
"""
    else:
        prompt = f"""다음 질문에 답하라. 현재 임베딩 기반 검색을 사용할 수 없으므로, 일반 지식으로만 답하되 불확실하면 그렇게 밝혀라.

질문:
{question}
"""
    answer = ollama.generate(model=gen_model, prompt=prompt, options={"temperature": temperature})["response"]
    if embed_error and not filtered_docs:
        answer = answer + f"\n\n[주의] embedding 검색 비활성화: {embed_error}"
    return {"question": question, "answer": answer, "contexts": filtered_docs, "sources": sources, "embed_model": embed_model, "gen_model": gen_model, "embedding_enabled": embedding_enabled, "embed_error": embed_error, "temperature": temperature}


