def normalize_text(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = [ln.rstrip() for ln in text.split("\n")]
    text = "\n".join(lines)
    text = "\n".join(line for line in text.split("\n") if line.strip())
    return text.strip()


def safe_stem(name: str) -> str:
    stem = Path(name).stem
    for ch in [" ", "/", "\\", ":", "*", "?", '"', "<", ">", "|"]:
        stem = stem.replace(ch, "_")
    return stem


def detect_language_hint(text: str) -> str:
    if not text:
        return "unknown"
    hangul = sum(1 for ch in text if "\uac00" <= ch <= "\ud7a3")
    latin = sum(1 for ch in text if ch.isascii() and ch.isalpha())
    if hangul > latin:
        return "ko"
    if latin > hangul:
        return "en"
    return "mixed"


def estimate_noise_score(text: str) -> dict:
    if not text:
        return {"score": 100.0, "level": "EMPTY", "usable": False, "reason": "empty text", "metrics": {}}

    chars = len(text)
    lines = [ln for ln in text.split("\n") if ln.strip()]
    line_count = max(1, len(lines))
    letters = sum(1 for ch in text if ch.isalpha())
    digits = sum(1 for ch in text if ch.isdigit())
    control = sum(1 for ch in text if ord(ch) < 32 and ch not in "\n\t")
    replacement = text.count("")

    short_lines = sum(1 for ln in lines if len(ln.strip()) < 20)
    short_line_ratio = short_lines / line_count

    repeat_runs = 0
    prev = ""
    run = 0
    for ch in text:
        if ch == prev:
            run += 1
        else:
            run = 1
            prev = ch
        if run >= 5:
            repeat_runs += 1

    alpha_ratio = letters / chars
    digit_ratio = digits / chars
    ctrl_ratio = control / chars
    repl_ratio = replacement / chars

    score = 0.0
    score += max(0, (1 - alpha_ratio)) * 12
    score += min(1, digit_ratio * 3) * 6
    score += min(1, ctrl_ratio * 25) * 35
    score += min(1, repl_ratio * 40) * 40
    score += min(1, short_line_ratio) * 10
    score += min(1, repeat_runs / 20) * 8
    score = max(0.0, min(100.0, score))

    if score >= 70:
        level, usable = "HIGH", False
    elif score >= 40:
        level, usable = "MEDIUM", True
    elif score >= 15:
        level, usable = "LOW", True
    else:
        level, usable = "GOOD", True

    reason = "ok"
    if replacement > 0:
        reason = "replacement chars detected"
    elif control > 0:
        reason = "control chars detected"
    elif short_line_ratio > 0.5:
        reason = "many short lines"
    elif repeat_runs > 0:
        reason = "repeated patterns detected"

    return {
        "score": round(score, 1),
        "level": level,
        "usable": usable,
        "reason": reason,
        "metrics": {
            "chars": chars,
            "alpha_ratio": round(alpha_ratio, 3),
            "digit_ratio": round(digit_ratio, 3),
            "ctrl_ratio": round(ctrl_ratio, 3),
            "repl_ratio": round(repl_ratio, 3),
            "short_line_ratio": round(short_line_ratio, 3),
            "repeat_runs": repeat_runs,
        },
    }

