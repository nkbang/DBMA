def extract_text(path: Path, use_ocr: bool = False) -> str:
    ext = path.suffix.lower()
    if ext == ".pdf":
        return extract_pdf(path, use_ocr=use_ocr)
    if ext == ".txt":
        return extract_txt(path)
    if ext == ".md":
        return extract_md(path)
    if ext == ".docx":
        return extract_docx(path)
    if ext == ".epub":
        return extract_epub(path)
    if ext in {".html", ".htm"}:
        return extract_html(path)
    if ext == ".rtf":
        return extract_rtf(path)
    return ""


def clean_text(text: str) -> str:
    text = normalize_text(text)
    text = text.replace("\xa0", " ")
    text = "\n".join(line.strip() for line in text.split("\n"))
    text = "\n".join(line for line in text.split("\n") if line.strip())
    return text.strip()


def chunk_text(text: str, chunk_size: int = None, chunk_overlap: int = None,
               doc_type: str = "default") -> tuple[list[str], dict]:
    """
    옵티마이저 우선 실행.
    chunk_size/chunk_overlap 이 명시적으로 전달되면 단회성 청킹(기존 호환).
    반환: (chunks, params)
    """
    from core.chunking_optimizer import chunk_once, optimize_chunks
    if chunk_size and chunk_overlap:
        result = chunk_once(text, chunk_size, chunk_overlap)
    else:
        result = optimize_chunks(text, doc_type)
    return result.chunks, result.params


